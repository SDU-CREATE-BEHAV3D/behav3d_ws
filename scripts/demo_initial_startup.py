"""Persistent synthetic startup demonstration; never use for a real scene.

The only input scene is generated by the labelled software fixture. The explicit
test-approval flag exercises post-approval planning, not a human's approval.
No ROS, camera, network, motion or extrusion code is invoked.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


def _write(path, value):
    with path.open("x", encoding="utf-8") as stream:
        json.dump(value, stream, indent=2, allow_nan=False)
        stream.write("\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--agent007-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--synthetic-software-test-approvals", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    agent = args.agent007_root.resolve(strict=True)
    sys.path[:0] = [str(root), str(root / "src/behav3d_orchestrator"), str(agent / "src"), str(agent)]
    from behav3d_orchestrator.supervised_agent.initial_workflow import (
        StartupSupervisor,
        evaluate_initial_wall,
    )
    from ocsr.initial_scene import export_scene, file_digest

    from tools.startup_validation.fixtures import create_source_scene, task_example

    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    inputs, products = output / "inputs", output / "products"
    inputs.mkdir()
    products.mkdir()
    source = create_source_scene(inputs / "source")
    scene = inputs / "scene"
    export_scene(source, scene, frame_id="startup_test_world")
    task = inputs / "task.json"
    _write(task, task_example())
    request = {"phase": "PROPOSE", "request_id": "synthetic-control-startup",
               "artifact_id": "synthetic-wall-300", "frame_id": "startup_test_world",
               "scene_manifest_path": str(scene / "manifest.json"),
               "scene_manifest_sha256": file_digest(scene / "manifest.json"),
               "task_path": str(task), "task_sha256": file_digest(task),
               "proposal_path": "", "proposal_sha256": ""}
    _write(output / "request.json", request)
    journal = output / "startup.jsonl"
    supervisor = StartupSupervisor(journal)

    def operation(value):
        return evaluate_initial_wall(value, input_roots=[str(inputs)], output_root=str(products),
                                     agent007_root=str(agent), behav3d_root=str(root),
                                     approval_journal_path=str(journal))

    summary = {"schema": "behav3d.initial_startup_demo.v1", "synthetic_fixture_only": True,
               "software_test_approvals_only": args.synthetic_software_test_approvals,
               "real_recorded_scene_approved": False, "robot_commands_sent": False,
               "fabrication_authorized": False, "scene": str(scene), "request": request}
    try:
        supervisor.set_armed(True, "synthetic-demo-preparation-not-human")
        proposed = supervisor.execute(request, lambda: operation(request))
        summary["proposal"] = proposed
        if not proposed["success"]:
            raise RuntimeError(proposed["message"])
        if list(products.rglob("targets.yaml")) or list(products.rglob("field_state_init.npz")):
            raise RuntimeError("Proposal-only phase unexpectedly created candidates")
        summary["no_candidates_before_approval"] = True
        if args.synthetic_software_test_approvals:
            supervisor.approve(request["request_id"], proposed["proposal_sha256"],
                               "synthetic-software-test-operator-not-human")
            generated_request = dict(request, phase="GENERATE", proposal_path=proposed["proposal_path"],
                                     proposal_sha256=proposed["proposal_sha256"])
            generated = supervisor.execute(generated_request, lambda: operation(generated_request))
            summary["generated"] = generated
            if not generated["success"]:
                raise RuntimeError(generated["message"])
            batch_path = Path(generated["batch_manifest_path"])
            if hashlib.sha256(batch_path.read_bytes()).hexdigest() != generated["batch_manifest_sha256"]:
                raise RuntimeError("Generated manifest changed")
            batch = json.loads(batch_path.read_text())
            summary["candidate_count"] = batch["candidate_count"]
            summary["requested_count"] = batch["requested_count"]
            summary["partial_batch"] = batch["partial_batch"]
        summary["passed"] = True
    except Exception as error:  # noqa: BLE001 -- persist an inspectable failed demo receipt
        summary.update(passed=False, error=str(error))
    finally:
        supervisor.set_armed(False, "synthetic-demo-ended-disarmed")
        summary["final_state"] = supervisor.snapshot()["state"]
        supervisor.close()
        _write(output / "summary.json", summary)
    print(json.dumps(summary, indent=2))
    return 0 if summary["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
